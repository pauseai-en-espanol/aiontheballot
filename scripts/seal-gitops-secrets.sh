#!/usr/bin/env bash
# Generates the aiontheballot database passwords and seals every aiontheballot secret for the cluster into a
# gitops checkout (ADR-0001). Nothing secret is printed or written unencrypted: passwords live in shell
# variables and reach kubectl through /dev/fd (process substitution), never through argv or a file.
#
# Usage: scripts/seal-gitops-secrets.sh <path-to-gitops>
# Asks for the secret of the registry's pull-only account, REGISTRY_ROBOT (input hidden), and seals it as the pull
# secret REGISTRY_PULL_SECRET. Refuses to overwrite: to rotate, delete the files first. The five passwords are always
# regenerated together, and the database's provisioning (gitops) re-applies them to the roles on its next sync. To
# replace the pull secret alone, scripts/seal-registry-pull-secret.sh.
# (scripts/seal-auth-role-secret.sh added the fifth, Better Auth's, to an existing checkout once.)
set -euo pipefail
set +x # a trace would print the secrets
# Never exported to the tools below, even if the caller's shell exports this name.
unset REGISTRY_SECRET

GITOPS="${1:?usage: $0 <path-to-gitops>}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
# The cluster's settings come from the environment or .env (scripts/lib/settings.sh, PLAN R205). KUBESEAL_ARGS
# names the cluster's context and sealing controller, or is "--cert cert.pem" for a dry run against a throwaway
# certificate.
. "$ROOT/scripts/lib/settings.sh"
for tool in jq kubectl kubeseal openssl; do
  command -v "$tool" >/dev/null || { echo "$tool is missing" >&2; exit 1; }
done
kubeseal_args=$(required KUBESEAL_ARGS)
read -r -a KUBESEAL_ARGS <<<"$kubeseal_args"

PG_DIR="$GITOPS/$(required GITOPS_DATABASE_DIR)"
APP_DIR="$GITOPS/$(required GITOPS_SECRETS_DIR)"
DB_HOST=$(required DATABASE_SERVICE)
DATABASE_NAMESPACE=$(required DATABASE_NAMESPACE)
REGISTRY_HOST=$(required REGISTRY_HOST)
REGISTRY_ROBOT=$(required REGISTRY_ROBOT)
REGISTRY_PULL_SECRET=$(required REGISTRY_PULL_SECRET)

files=("$PG_DIR/aiontheballot-db-credentials.yaml" "$APP_DIR/$REGISTRY_PULL_SECRET.yaml"
  "$APP_DIR/aiontheballot-owner-db.yaml" "$APP_DIR/aiontheballot-web-db.yaml" "$APP_DIR/aiontheballot-admin-db.yaml"
  "$APP_DIR/aiontheballot-worker-db.yaml" "$APP_DIR/aiontheballot-auth-db.yaml"
  "$APP_DIR/aiontheballot-better-auth.yaml")
for f in "${files[@]}"; do
  if [ -e "$f" ]; then
    echo "Refusing to overwrite $f" >&2
    exit 1
  fi
done
[ -d "$PG_DIR" ] || { echo "Not a gitops checkout: $PG_DIR is missing" >&2; exit 1; }
mkdir -p "$APP_DIR"

# seal <out> <header> <wave|-> <kubectl create secret args...>
# Writes header comments plus the SealedSecret. Secrets in the app namespace get sync wave -2, so Argo CD creates them
# before the migration Job (wave -1) and the Deployments (wave 0).
seal() {
  local out="$1" header="$2" wave="$3"
  shift 3
  local tmp="$out.tmp"
  if ! {
    printf '# yamllint disable rule:line-length\n'
    printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
    printf '%s\n' "$header"
    kubectl create secret "$@" --dry-run=client -o yaml \
      | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
      | if [ "$wave" = - ]; then sed '/^---$/d'; else
          kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=$wave" -o yaml
        fi
  } >"$tmp" || ! grep -q '^kind: SealedSecret$' "$tmp"; then
    rm -f "$tmp"
    echo "Failed to seal $out" >&2
    exit 1
  fi
  mv "$tmp" "$out"
  echo "sealed $out"
}

printf 'Secret of %s on %s: ' "$REGISTRY_ROBOT" "$REGISTRY_HOST"
IFS= read -rs REGISTRY_SECRET || true
echo
[ -n "$REGISTRY_SECRET" ] || { echo "Empty registry secret" >&2; exit 1; }
# Built before sealing, so a failure stops here rather than sealing an empty config; the secret reaches jq on stdin.
pull_config=$(printf '%s' "$REGISTRY_SECRET" | jq -Rsc --arg host "$REGISTRY_HOST" --arg robot "$REGISTRY_ROBOT" '
  {auths: {($host): {username: $robot, password: ., auth: ("\($robot):\(.)" | @base64)}}}')
unset REGISTRY_SECRET

owner_pw="$(openssl rand -hex 32)"
web_pw="$(openssl rand -hex 32)"
admin_pw="$(openssl rand -hex 32)"
worker_pw="$(openssl rand -hex 32)"
auth_pw="$(openssl rand -hex 32)"
auth_secret="$(openssl rand -hex 32)"
url() { printf 'postgres://%s:%s@%s/aiontheballot?sslmode=disable' "$1" "$2" "$DB_HOST"; }

seal "$PG_DIR/aiontheballot-db-credentials.yaml" \
  "# Read by the database's provisioning: owner and extra-role passwords for the aiontheballot database
# (openssl rand -hex 32 each). Each must match DATABASE_URL in aiontheballot/aiontheballot-<role>-db.
# Generated by scripts/seal-gitops-secrets.sh in pauseai-en-espanol/aiontheballot." - \
  generic aiontheballot-db-credentials -n "$DATABASE_NAMESPACE" \
  --from-file=AIONTHEBALLOT_OWNER_PASSWORD=<(printf %s "$owner_pw") \
  --from-file=AIONTHEBALLOT_WEB_PASSWORD=<(printf %s "$web_pw") \
  --from-file=AIONTHEBALLOT_ADMIN_PASSWORD=<(printf %s "$admin_pw") \
  --from-file=AIONTHEBALLOT_WORKER_PASSWORD=<(printf %s "$worker_pw") \
  --from-file=AIONTHEBALLOT_AUTH_PASSWORD=<(printf %s "$auth_pw")

seal "$APP_DIR/$REGISTRY_PULL_SECRET.yaml" \
  "# Pull secret for $REGISTRY_HOST/aiontheballot ($REGISTRY_ROBOT, pull only), on the default SA." -2 \
  generic "$REGISTRY_PULL_SECRET" -n aiontheballot --type=kubernetes.io/dockerconfigjson \
  --from-file=.dockerconfigjson=<(printf '%s' "$pull_config")

seal "$APP_DIR/aiontheballot-owner-db.yaml" \
  "# DATABASE_URL for aiontheballot_owner (migrations only): $(url aiontheballot_owner '<OWNER_PASSWORD>')" -2 \
  generic aiontheballot-owner-db -n aiontheballot --from-file=DATABASE_URL=<(url aiontheballot_owner "$owner_pw")

# The runtime URLs are sealed now so each password is generated once; the API and worker use them from M1.
seal "$APP_DIR/aiontheballot-web-db.yaml" \
  "# DATABASE_URL for aiontheballot_web (API public routes, read-only): $(url aiontheballot_web '<WEB_PASSWORD>')" -2 \
  generic aiontheballot-web-db -n aiontheballot --from-file=DATABASE_URL=<(url aiontheballot_web "$web_pw")

seal "$APP_DIR/aiontheballot-admin-db.yaml" \
  "# DATABASE_URL for aiontheballot_admin (API admin routes): $(url aiontheballot_admin '<ADMIN_PASSWORD>')" -2 \
  generic aiontheballot-admin-db -n aiontheballot --from-file=DATABASE_URL=<(url aiontheballot_admin "$admin_pw")

seal "$APP_DIR/aiontheballot-worker-db.yaml" \
  "# DATABASE_URL for aiontheballot_worker (background worker): $(url aiontheballot_worker '<WORKER_PASSWORD>')" -2 \
  generic aiontheballot-worker-db -n aiontheballot --from-file=DATABASE_URL=<(url aiontheballot_worker "$worker_pw")

seal "$APP_DIR/aiontheballot-auth-db.yaml" \
  "# DATABASE_URL for aiontheballot_auth (Better Auth, in the API): $(url aiontheballot_auth '<AUTH_PASSWORD>')" -2 \
  generic aiontheballot-auth-db -n aiontheballot --from-file=DATABASE_URL=<(url aiontheballot_auth "$auth_pw")

seal "$APP_DIR/aiontheballot-better-auth.yaml" \
  "# BETTER_AUTH_SECRET: the key Better Auth signs sessions and tokens with (openssl rand -hex 32)." -2 \
  generic aiontheballot-better-auth -n aiontheballot --from-file=BETTER_AUTH_SECRET=<(printf %s "$auth_secret")

unset REGISTRY_SECRET owner_pw web_pw admin_pw worker_pw auth_pw auth_secret
echo "Done. Review with: git -C \"$GITOPS\" status"
