#!/usr/bin/env bash
# Seals an archive.org account's S3 keys for the fetcher's snapshots (ADR-0007, PLAN R175) into a gitops checkout, as
# aiontheballot-fetcher-archive with keys ARCHIVE_ACCESS_KEY and ARCHIVE_SECRET_KEY. Optional: without them Save Page
# Now allows far fewer captures (3 a minute and 200 a day, against 7 and 30,000). Get them, signed in to the account,
# at https://archive.org/account/s3.php. They are read from the terminal without being shown, never printed or written
# unencrypted: they live in shell variables and reach kubectl through /dev/fd.
#
# Usage: scripts/seal-fetcher-archive-keys.sh <path-to-gitops>
# Refuses to overwrite: to rotate, delete the file first, seal again, and restart the fetcher once Argo has synced.
# Then list the secret in the fetcher's envFrom (aiontheballot-api.fetcher.envFrom).
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
# The cluster's settings come from the environment or .env (scripts/lib/settings.sh, PLAN R205). KUBESEAL_ARGS
# names the cluster's context and sealing controller, or is "--cert cert.pem" for a dry run against a throwaway
# certificate.
. "$ROOT/scripts/lib/settings.sh"
kubeseal_args=$(required KUBESEAL_ARGS)
read -r -a KUBESEAL_ARGS <<<"$kubeseal_args"

APP_DIR="$GITOPS/$(required GITOPS_SECRETS_DIR)"
out="$APP_DIR/aiontheballot-fetcher-archive.yaml"

fail() {
  echo "$1" >&2
  exit 1
}
[ -d "$APP_DIR" ] || fail "Not a gitops checkout with aiontheballot secrets: $APP_DIR is missing"
[ ! -e "$out" ] || fail "Refusing to overwrite $out"

# Written beside its target and moved into place only at the end, so an interruption leaves the checkout as it was.
trap 'rm -f "$out.tmp"' EXIT

read -r -s -p 'archive.org S3 access key: ' access
echo
read -r -s -p 'archive.org S3 secret key: ' secret
echo
[ -n "$access" ] && [ -n "$secret" ] || fail 'Both keys are needed'

# At sync wave -2 like the other app secrets: created before the Deployments (wave 0).
{
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf "# ARCHIVE_ACCESS_KEY, ARCHIVE_SECRET_KEY: an archive.org account's S3 keys, for the fetcher (app repo ADR-0007).\n"
  printf '# Generated by scripts/seal-fetcher-archive-keys.sh in pauseai-en-espanol/aiontheballot.\n'
  kubectl create secret generic aiontheballot-fetcher-archive -n aiontheballot --dry-run=client -o yaml \
    --from-file=ARCHIVE_ACCESS_KEY=<(printf %s "$access") \
    --from-file=ARCHIVE_SECRET_KEY=<(printf %s "$secret") \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$out.tmp" || fail "Failed to seal $out"
mv "$out.tmp" "$out"
unset access secret
echo "sealed $out"
echo "Done. Review with: git -C \"$GITOPS\" status"
