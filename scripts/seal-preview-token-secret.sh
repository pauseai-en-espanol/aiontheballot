#!/usr/bin/env bash
# Seals the secret the admin and the web app share for previewing a site (ADR-0005, PLAN R174) into a gitops checkout,
# as aiontheballot-preview-token with key token: the admin sends it with every preview request, and the web app serves
# its preview host to nothing without it. A random 64-character value, never printed or written unencrypted: it lives
# in a shell variable and reaches kubectl through /dev/fd.
#
# Usage: scripts/seal-preview-token-secret.sh <path-to-gitops>
# Refuses to overwrite: to rotate, delete the file first, seal again, and restart both the admin and the web app once
# Argo has synced (each reads it at startup). Then name the secret in the app's values
# (aiontheballot-web.preview.tokenSecret.name and aiontheballot-admin.preview.tokenSecret.name).
set -euo pipefail

GITOPS="${1:?usage: $0 <path-to-gitops>}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
# The cluster's settings come from the environment or .env (scripts/lib/settings.sh, PLAN R205). KUBESEAL_ARGS
# names the cluster's context and sealing controller, or is "--cert cert.pem" for a dry run against a throwaway
# certificate.
. "$ROOT/scripts/lib/settings.sh"
kubeseal_args=$(required KUBESEAL_ARGS)
read -r -a KUBESEAL_ARGS <<<"$kubeseal_args"

APP_DIR="$GITOPS/$(required GITOPS_SECRETS_DIR)"
out="$APP_DIR/aiontheballot-preview-token.yaml"

fail() {
  echo "$1" >&2
  exit 1
}
[ -d "$APP_DIR" ] || fail "Not a gitops checkout with aiontheballot secrets: $APP_DIR is missing"
[ ! -e "$out" ] || fail "Refusing to overwrite $out"

# Written beside its target and moved into place only at the end, so an interruption leaves the checkout as it was.
trap 'rm -f "$out.tmp"' EXIT

token="$(openssl rand -hex 32)"

# At sync wave -2 like the other app secrets: created before the Deployments (wave 0).
{
  printf '# yamllint disable rule:line-length\n'
  printf '# SealedSecret encryptedData contains long base64 strings that cannot be wrapped.\n'
  printf '# token: the secret the admin and the web app share for previewing a site (app repo ADR-0005).\n'
  printf '# Generated by scripts/seal-preview-token-secret.sh in pauseai-en-espanol/aiontheballot.\n'
  kubectl create secret generic aiontheballot-preview-token -n aiontheballot --dry-run=client -o yaml \
    --from-file=token=<(printf %s "$token") \
    | kubeseal "${KUBESEAL_ARGS[@]}" --format yaml \
    | kubectl annotate --local -f - "argocd.argoproj.io/sync-wave=-2" -o yaml
} >"$out.tmp" || fail "Failed to seal $out"
mv "$out.tmp" "$out"
unset token
echo "sealed $out"
echo "Done. Review with: git -C \"$GITOPS\" status"
