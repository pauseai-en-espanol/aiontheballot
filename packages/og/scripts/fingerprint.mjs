// Fingerprints every share-image template from its probe renders (src/fingerprint.ts) and writes them over the
// compiled stub in dist/fingerprints.js, which cardHash folds into every image's URL (PLAN R147). Run by `build` and
// `prepare`, right after tsc, so it also runs in Docker builds (where prepare is skipped) and on fresh installs.
import { writeFile } from 'node:fs/promises';

const { fingerprintAll } = await import('../dist/fingerprint.js');
const fingerprints = await fingerprintAll();
const target = new URL('../dist/fingerprints.js', import.meta.url);
await writeFile(
  target,
  "// Generated by scripts/fingerprint.mjs at build time: each template's probe renders, digested.\n" +
    `export const FINGERPRINTS = Object.freeze(${JSON.stringify(fingerprints, null, 2)});\n`,
);
console.log(
  `Share-image fingerprints: ${Object.entries(fingerprints)
    .map(([template, fingerprint]) => `${template} ${fingerprint}`)
    .join(', ')}`,
);
